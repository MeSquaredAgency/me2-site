// Builds the fixture (test-only) version of the site (BRIEF §6b): every [[TBC]] filled with
// reserved fake values so flagged features can be checked before the real values exist.
// It is noindex, uses example.com, and must never be deployed.
//
// Usage: node scripts/build-fixture.mjs [outDir] [flagsJson]
//   outDir    default .verify/fixture/dist
//   flagsJson default: every flag on, e.g. '{"showPricing":true}' for one flag alone
import { mkdirSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';

const outDir = process.argv[2] ?? '.verify/fixture/dist';
const allOn = {
  showPricing: true, showProof: true, showLocations: true, showLegalEntity: true,
  showPrivacyPage: true, enableContactForm: true, enableBooking: true, enableTracking: true,
};
const flagsJson = process.argv[3] ?? JSON.stringify(allOn);

mkdirSync('.verify/fixture', { recursive: true });
writeFileSync('.verify/fixture/overrides.ts', `// Generated by scripts/build-fixture.mjs. Test values only; never deploy.
export const config = {
  SITE_DOMAIN: 'example.com',
  CONTACT_EMAIL: 'test@example.com',
  PRIVACY_EMAIL: 'test@example.com',
  FORM_FROM_EMAIL: 'test@example.com',
  FORM_TO_EMAIL: 'test@example.com',
  BOOKING_URL: 'https://example.com/book',
  LEGAL_ENTITY: 'Test Entity Pty Ltd, ABN 00 000 000 000',
};
export const flags = {};
export const content = {
  price: 'From $1 AUD per test',
  proof: 'Test Customer said this is a test.',
  privacy: 'Test privacy policy.',
};
`);

const env = { ...process.env, SITE_FIXTURE: '1', FIXTURE_FLAGS: flagsJson, OUT_DIR: outDir };
execSync(`npx astro build --outDir "${outDir}"`, { stdio: 'inherit', env });
execSync('node scripts/postbuild.mjs', { stdio: 'inherit', env });
